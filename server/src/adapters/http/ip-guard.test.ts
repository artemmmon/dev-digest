import { describe, it, expect } from 'vitest';
import { isBlockedAddress } from './ip-guard.js';

describe('isBlockedAddress', () => {
  const blocked = [
    '0.0.0.0', '10.1.2.3', '100.64.0.1', '100.127.255.255', '127.0.0.1', '127.255.0.9',
    '169.254.169.254', '172.16.0.1', '172.31.255.255', '192.168.1.1', '192.0.0.8', '198.18.0.1',
    '224.0.0.1', '239.255.255.250', '240.0.0.1', '255.255.255.255',
    '::', '::1', '::ffff:127.0.0.1', '::ffff:7f00:1', '::ffff:10.0.0.1', '::ffff:a9fe:a9fe',
    '::127.0.0.1', '64:ff9b::7f00:1', '2002:7f00:1::1', 'fc00::1', 'fd12:3456::1', 'fe80::1',
    'fe80::1%eth0', 'febf::1', 'ff02::1', '2001:db8::1', '2001::1',
    'not-an-ip', '', '1.2.3', '256.1.1.1', '::g',
  ];
  const allowed = [
    '1.1.1.1', '8.8.8.8', '93.184.216.34', '100.63.255.255', '100.128.0.1', '172.15.255.255',
    '172.32.0.1', '169.253.1.1', '192.169.0.1', '198.20.0.1', '223.255.255.255',
    '2606:4700:4700::1111', '2a00:1450:4001:81a::200e', '::ffff:8.8.8.8', '64:ff9b::808:808',
    '2002:808:808::1', '2001:4860:4860::8888',
  ];

  it.each(blocked)('blocks %j', (ip) => {
    expect(isBlockedAddress(ip)).toBe(true);
  });
  it.each(allowed)('allows %s', (ip) => {
    expect(isBlockedAddress(ip)).toBe(false);
  });
});
